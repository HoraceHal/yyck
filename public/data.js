/* 粵語通 · 课程数据
 * W(粤语, 粤拼, 普通话释义, 备注)         —— 词
 * P(普通话释义, [词,粤拼], [词,粤拼], ...)  —— 句子(按词切分,用于"排序题")
 * 规则:每个汉字对应一个粤拼音节,标点不占音节。
 */
const fw = s => s.replace(/,/g, '，').replace(/\?/g, '？').replace(/!/g, '！');
const W = (c, j, m, n) => ({ k: 'w', c, j, m: fw(m), n: n || '' });
const P = (m, ...ws) => {
  ws = ws.map(x => [fw(x[0]), x[1]]);
  return { k: 'p', c: ws.map(x => x[0]).join(''), j: ws.map(x => x[1]).join(' '), m: fw(m), w: ws };
};

